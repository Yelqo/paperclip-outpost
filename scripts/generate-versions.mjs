import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const read = path => readFileSync(resolve(root, path), 'utf8');
const lock = JSON.parse(read('upstream/paperclip.lock.json'));
const release = JSON.parse(read('package.json')).version;
// The plugin and daemon ship together in the same Outpost release.
const versions = { host: lock.commit, sdk: lock.sdk, plugin: release, daemon: release, protocol: lock.transport };
const banner = 'Generated by scripts/generate-versions.mjs; do not edit.';
const goFields = { host: 'Host', sdk: 'SDK', plugin: 'Plugin', daemon: 'Daemon', protocol: 'Protocol' };
const goSource = `// Code generated by scripts/generate-versions.mjs; DO NOT EDIT.\n\npackage outpost\n\nvar supported = Versions{\n${Object.entries(versions).map(([key, value]) => `\t${(goFields[key] + ':').padEnd(10)}${JSON.stringify(value)},`).join('\n')}\n}\n`;

const patchPath = `upstream/${lock.patch}`;
let patch = read(patchPath);
// The carried host implementation advertises the same SDK/transport contract.
for (const [pattern, replacement] of [
  [/^\+export const PLUGIN_WEBSOCKET_SDK_VERSION = .*;$/gm, `+export const PLUGIN_WEBSOCKET_SDK_VERSION = ${JSON.stringify(versions.sdk)};`],
  [/^\+  const host = \{ commit, sdk: PLUGIN_WEBSOCKET_SDK_VERSION, transport: \d+ \};$/gm, `+  const host = { commit, sdk: PLUGIN_WEBSOCKET_SDK_VERSION, transport: ${versions.protocol} };`],
]) {
  if ([...patch.matchAll(pattern)].length !== 1) throw new Error('Cannot locate the host compatibility declaration in the patch');
  patch = patch.replace(pattern, replacement);
}

const outputs = new Map([
  ['plugin/versions.ts', `// ${banner}\nexport const versions = ${JSON.stringify(versions, null, 2)} as const;\n`],
  ['internal/outpost/versions.go', goSource],
  [patchPath, patch],
]);
const stale = [];
for (const [path, expected] of outputs) {
  const target = resolve(root, path);
  if (existsSync(target) && readFileSync(target, 'utf8') === expected) continue;
  stale.push(path);
  if (!process.argv.includes('--check')) writeFileSync(target, expected);
}
if (process.argv.includes('--check') && stale.length) {
  throw new Error(`Stale compatibility declarations: ${stale.join(', ')}. Run pnpm generate:versions.`);
}
