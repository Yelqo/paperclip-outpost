import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const read = path => readFileSync(resolve(root, path), 'utf8');
const lock = JSON.parse(read('upstream/paperclip.lock.json'));
const release = JSON.parse(read('package.json')).version;
// The plugin and daemon ship together in the same Outpost release.
const versions = { host: lock.commit, sdk: lock.sdk, shared: lock.shared, plugin: release, daemon: release, protocol: lock.transport };
const banner = 'Generated by scripts/generate-versions.mjs; do not edit.';
const goFields = { host: 'Host', sdk: 'SDK', shared: 'Shared', plugin: 'Plugin', daemon: 'Daemon', protocol: 'Protocol' };
const goSource = `// Code generated by scripts/generate-versions.mjs; DO NOT EDIT.\n\npackage outpost\n\nvar supported = Versions{\n${Object.entries(versions).map(([key, value]) => `\t${(goFields[key] + ':').padEnd(10)}${JSON.stringify(value)},`).join('\n')}\n}\n`;

function replaceDeclarations(patch, replacements, integration) {
  for (const [pattern, replacement] of replacements) {
    if ([...patch.matchAll(pattern)].length !== 1) throw new Error(`Cannot locate the ${integration} compatibility declaration in the patch`);
    patch = patch.replace(pattern, replacement);
  }
  return patch;
}

const patchPath = `upstream/${lock.patch}`;
// The carried host implementation advertises the same SDK/transport contract.
const patch = replaceDeclarations(read(patchPath), [
  [/^\+export const PLUGIN_WEBSOCKET_SDK_VERSION = .*;$/gm, `+export const PLUGIN_WEBSOCKET_SDK_VERSION = ${JSON.stringify(versions.sdk)};`],
  [/^\+  const host = \{ commit, sdk: PLUGIN_WEBSOCKET_SDK_VERSION, shared, transport: \d+ \};$/gm, `+  const host = { commit, sdk: PLUGIN_WEBSOCKET_SDK_VERSION, shared, transport: ${versions.protocol} };`],
], 'host');

const outputs = new Map([
  ['plugin/versions.ts', `// ${banner}\nexport const versions = ${JSON.stringify(versions, null, 2)} as const;\n`],
  ['internal/outpost/versions.go', goSource],
  [patchPath, patch],
]);
const pi = JSON.parse(read('upstream/pi-config.lock.json'));
const piPatchPath = `upstream/${pi.patch}`;
const piPatch = replaceDeclarations(read(piPatchPath), [
  [/^\+const outpostRuntimeVersions = .*;$/gm, `+const outpostRuntimeVersions = ${JSON.stringify({host:versions.host,piConfig:pi.commit,pi:pi.pi,node:pi.node})};`],
  [/^\+export const paperclipRevision = .*;$/gm, `+export const paperclipRevision = ${JSON.stringify(versions.host)};`],
], 'Pi');
outputs.set(piPatchPath,piPatch);
const compatibility = {
  ...versions, pi:pi.pi, piConfig:pi.commit, node:pi.node,
  hostPatchSHA256:createHash('sha256').update(patch).digest('hex'),
  piConfigPatchSHA256:createHash('sha256').update(piPatch).digest('hex'),
};
outputs.set('release/compatibility.json',JSON.stringify(compatibility,null,2)+'\n');
const stale = [];
for (const [path, expected] of outputs) {
  const target = resolve(root, path);
  if (existsSync(target) && readFileSync(target, 'utf8') === expected) continue;
  stale.push(path);
  if (!process.argv.includes('--check')) {
    mkdirSync(dirname(target),{recursive:true});
    writeFileSync(target, expected);
  }
}
if (process.argv.includes('--check') && stale.length) {
  throw new Error(`Stale compatibility declarations: ${stale.join(', ')}. Run pnpm generate:versions.`);
}
